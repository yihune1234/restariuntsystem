export const useI18nStore = create(
  persist(
    (set) => ({
      lang: "en",
      setLang: (lang) => set({ lang }),
    }),
    { name: "i18n-storage" }
  )
);

/** Translate a key in the active language. Falls back to English then the key. */
export function useTranslation() {
  const lang = useI18nStore((s) => s.lang);
  const t = (key, fallback) => {
    const row = messages[lang]?.[key] ?? messages.en[key] ?? key;
    if (row !== key) return row;
    return fallback ?? key;
  };
  return { t, lang };
}